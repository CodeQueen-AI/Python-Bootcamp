# Concatenation (+)
first_name = "Code"
last_name = "Queen"
full_name = first_name + " " + last_name
print(full_name)  

# Repetition (*)
repeat_name = "Code " * 3
print(repeat_name) 

# Indexing ([])
word = "Python"
print(word[0])  
print(word[-1])

# Slicing ([:])
print(word[0:4])  
print(word[-4:])  

# Membership (in)
print("t" in word)  

# Membership (not in)
print("z" not in word)  